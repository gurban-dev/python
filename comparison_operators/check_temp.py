# The data type of the "temp_in_celsius" variable is an integer.
temp_in_celsius = 30
temp_in_fahrenheit = 86

# With 30 assigned to 'temp_in_celsius', the first condition evaluates
# to True, so the code inside the if block is executed.
if temp_in_celsius > 27:
	print("It's a hot day.")
elif temp_in_celsius > 20:
	print("It's a warm day.")
else:
	print("It's a chilly day.")

# The first condition also evaluates to True, so the code inside
# the if block is executed.
if temp_in_fahrenheit > 27:
	print("It's a hot day.")
elif temp_in_fahrenheit > 20:
	print("It's a warm day.")
else:
	print("It's a chilly day.")