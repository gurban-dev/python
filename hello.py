# Python has this built-in print() function.
print('Hello World!')

# The print() function will accept data and
# print it to the screen.
print(2)

# 3 is an integer because it is a number without
# quotation marks.
print(3 + 3)

# "3" is a string because it is a character with
# quotation marks.
print("3" + "3")

# Structure for variable declaration:
# <variable_name> = <value_assigned_to_the_variable>
given_name = 'Alexander'

print('given_name:', given_name)

