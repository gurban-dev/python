given_name = "Alexander"

# The string literal is the part of the code that has
# quotation marks hardcoded ("Alexander").

# Python's built-in type() function will return
# the data type of the argument passed to it.
# The data type is called str which is short for "string".
print('type(\"Alexander\"):', type("Alexander"))

# If "Alexander" is a string literal, then what is the
# the data type of the variable 'given_name'?

# The data types of variables are determined by the values
# assigned to them.
print('\ntype(given_name):', type(given_name))

# 10.0 is a float, so type(10.0) will return:
# <class 'float'>
print('\ntype(10.0):', type(10.0))