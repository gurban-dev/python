# Syntax:
# <variable_name> = <value_being_assigned_to_the_variable>

# What looks like an equals sign (=) is called
# the "assignment operator" in Python.

# E.g.
given_name = 'Alexander'

# How can the integer literal 115 be assigned to a variable named "age"?

age = 115

# When should integers and strings be used?
# If you have to perform an arithmetic operation
# (think of addition or subtraction), then you'd
# use an integer.

# If you have to construct a sentence, a string
# is appropriate.

monthly_salary = 2_500

# What if I want to keep track of whether Alexander lives
# in the city Gdansk?

# The variable "lives_in_gdansk" has a boolean
# data type because False is assigned to it.
# True and False are boolean values.
lives_in_gdansk = False