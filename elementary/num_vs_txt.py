# Is 2 + 2 numeric data or text data?
print("2 + 2:", 2 + 2)

# If you don't see quotation marks around numbers, that tells
# that they numeric.

# Why is "2" + "2" not considered numeric data?
print("\n\"2\" + \"2\":", "2" + "2")

# The quotation marks around the numbers makes them strings
# rather than integers.