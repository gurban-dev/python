# Addition
sum = 2 + 2

print('sum was assigned 2 + 2')

# sum: 4
print('\nsum:', sum)

# Subtraction
# Take the current value of 'sum' which is 4,
# and insert it into the 'sum' variable.
# sum = sum - 2 -> 4 - 2 -> 2
sum = sum - 2

print('\n\'sum\' after sum = sum - 2:', sum)

# Augmented assignment operator
sum -= 2

# Lines 11 and 16 are performing the same
# operation:
# 2 is being subtracted from the 'sum' variable.

print('\n\'sum\' after sum -= 2:', sum)

sum = -2

print('\nsum was assigned -2.\n\nsum:', sum)

# Take the current value of 'sum' and insert
# it into the following computation:
# sum = sum + 2 -> -2 + 2 -> 0
sum += 2

print('\n\'sum\' after sum += 2:', sum)