# 'english' and 'french' are variables that reference dictionary
# objects.

# Dictionaries are made up of key-value pairs where each key
# corresponds to a value.

# The key appears before the colon (:).
# The value appears after the space that follows the colon (:).

french = {
    # key: value
    "hello": "Bonjour",
    "goodbye": "Au revoir",

    # "thank you" is also valid as a dictionary key in Python,
    # but less common.
    "thank_you": "Merci"
}

